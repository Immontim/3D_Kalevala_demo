const TEXT: Record<Language, Record<TextKey, string>> = { fi: FI, en: EN };

function storedLanguage(): Language {
  try {
    const saved = typeof localStorage === "undefined" ? null : localStorage.getItem(LANGUAGE_STORE);
    if (saved === "en" || saved === "fi") return saved;
  } catch { /* tallennus ei ole käytössä */ }
  return "fi";
}

let language: Language = storedLanguage();

export function getLanguage(): Language { return language; }

/** Teksti aina suomeksi riippumatta valitusta kielestä (omistajalle tulostettavat yhteenvedot). */
export function finnishText(key: TextKey): string { return FI[key]; }

export function setLanguage(next: Language) {
  language = next;
  try { localStorage.setItem(LANGUAGE_STORE, next); } catch { /* valinta jää tähän istuntoon */ }
}

export function t(key: TextKey, params: Record<string, string | number> = {}): string {
  return TEXT[language][key].replace(/\{(\w+)\}/g, (whole, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : whole);
}

/** Kääntää index.html:n staattiset tekstit repo-sisäisistä, luotetuista sanakirjoista. */
export function translateDocument(root: ParentNode = document) {
  document.documentElement.lang = language;
  document.title = t("meta.title");
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n as TextKey);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml as TextKey);
  });
}

/** Sisältö, joka on tarkoituksella alkuperäiskielinen eikä kuulu käännössanakirjaan. */
export interface VerbatimText {
  readonly kind: "verbatim";
  readonly text: string;
  readonly lang: string;
  readonly source?: string;
}

export function verbatim(text: string, lang = "fi", source?: string): VerbatimText {
  return { kind: "verbatim", text, lang, source };
}

/** Asettaa myös selaimille ja konekääntäjille eksplisiittisen translate=no-tagin. */
export function renderVerbatim(el: HTMLElement, value: VerbatimText) {
  el.textContent = value.text;
  el.lang = value.lang;
  el.translate = false;
  el.classList.add("notranslate");
}
